/**
 * Get cities for a given state
 * @param state - The state name
 * @returns Array of cities for the state, or empty array if state not found
 */
export const getCitiesByState = (state: string): string[] => STATE_CITY_MAP[state] ?? []

/**
 * Get all states
 * @returns Array of all state names
 */
export const getAllStates = (): string[] => Object.keys(STATE_CITY_MAP)

/**
 * Check if a state exists
 * @param state - The state name
 * @returns True if state exists, false otherwise
 */
export const stateExists = (state: string): boolean => state in STATE_CITY_MAP

/**
 * Check if a city exists in a state
 * @param state - The state name
 * @param city - The city name
 * @returns True if city exists in the state, false otherwise
 */
export const cityExistsInState = (state: string, city: string): boolean => {
  const cities = getCitiesByState(state)
  return cities.includes(city)
}
